import * as React from "react";

export const WORDBOOK_STORAGE_KEY = "ndtVocabularyBook";

export function normalizeTermKey(term, language = "") {
  const cleanTerm = String(term || "")
    .trim()
    .replace(/\s+/g, " ")
    .toLowerCase();
  const cleanLang = String(language || "")
    .trim()
    .toLowerCase();
  return `${cleanLang}::${cleanTerm}`;
}

export function mapSubtitleLangToTtsSource(lan = "", lanDoc = "") {
  const raw = `${lan} ${lanDoc}`.toLowerCase();
  if (/\b(es|spa)\b|西班牙|español|spanish/.test(raw)) return "西班牙语";
  if (/\b(en|eng)\b|英语|英文|english/.test(raw)) return "英语";
  if (/\b(ja|jp|jpn)\b|日语|日文|日本語|japanese/.test(raw)) return "日语";
  if (/\b(ko|kr|kor)\b|韩语|韩文|한국어|korean/.test(raw)) return "韩语";
  if (/\b(fr|fra|fre)\b|法语|法文|français|french/.test(raw)) return "法语";
  if (/\b(de|deu|ger)\b|德语|德文|deutsch|german/.test(raw)) return "德语";
  if (/\b(it|ita)\b|意大利|italiano|italian/.test(raw)) return "意大利语";
  if (/\b(pt|por)\b|葡萄牙|português|portuguese/.test(raw)) return "葡萄牙语";
  if (/\b(ru|rus)\b|俄语|俄文|русский|russian/.test(raw)) return "俄语";
  if (/\b(nl|nld|dut)\b|荷兰|nederlands|dutch/.test(raw)) return "荷兰语";
  if (/\b(ar|ara)\b|阿拉伯|arabic/.test(raw)) return "阿拉伯语";
  if (/\b(th|tha)\b|泰语|thai/.test(raw)) return "泰语";
  if (/\b(tr|tur)\b|土耳其|turkish/.test(raw)) return "土耳其语";
  if (/\b(pl|pol)\b|波兰|polish/.test(raw)) return "波兰语";
  if (/\b(sv|swe)\b|瑞典|swedish/.test(raw)) return "瑞典语";
  if (/\b(id|ind)\b|印尼|indonesian/.test(raw)) return "印尼语";
  if (/\b(hi|hin)\b|印地|hindi/.test(raw)) return "印地语";
  if (/\b(el|ell|gre)\b|希腊|greek/.test(raw)) return "希腊语";
  if (/\b(zh|chi|zho)\b|中文|汉语|国语|普通话|繁體|简体|chinese/.test(raw)) {
    return /繁|tw|hk|hant/.test(raw) ? "中文(繁体)" : "中文(简体)";
  }
  return "";
}

export function isChineseSubtitleTrack(track) {
  if (!track) return false;
  const lan = String(track.lan || "").toLowerCase();
  const doc = String(track.lanDoc || "").toLowerCase();
  return /^(ai-)?zh([-_]|$)/.test(lan) || /中文|汉语|简体|繁体|繁體|国语/.test(doc);
}

export function pickRecommendedStudyTrack(tracks = [], targetLanguage = "中文(简体)") {
  if (!Array.isArray(tracks) || tracks.length === 0) return null;
  const playable = tracks.filter((t) => Array.isArray(t?.cues) && t.cues.length > 0);
  const fetchable = tracks.filter((t) => Boolean(t?.subtitleUrl || t?.hasSubtitleUrl));
  const pool = playable.length > 0 ? playable : fetchable.length > 0 ? fetchable : tracks;
  const targetIsZh = /中文/.test(String(targetLanguage || ""));

  // 1. Respect currently active CC track in player (e.g., user explicitly picked a YouTube CC track)
  const activeTrack = pool.find((t) => t?.isActiveInPlayer);
  if (activeTrack && (!targetIsZh || !isChineseSubtitleTrack(activeTrack) || pool.length === 1)) {
    return activeTrack;
  }

  // 2. Prefer video's original spoken language track (manual first, then ASR)
  const originalManual = pool.find(
    (t) => t?.isOriginalLang && !t?.isAutoGenerated && (!targetIsZh || !isChineseSubtitleTrack(t))
  );
  if (originalManual) return originalManual;

  const defaultCaption = pool.find(
    (t) => t?.isDefaultCaption && (!targetIsZh || !isChineseSubtitleTrack(t))
  );
  if (defaultCaption) return defaultCaption;

  const originalAny = pool.find(
    (t) => t?.isOriginalLang && (!targetIsZh || !isChineseSubtitleTrack(t))
  );
  if (originalAny) return originalAny;

  // 3. Fallback: if target is Chinese, pick first non-Chinese track (preferring English if present among many tracks)
  if (targetIsZh) {
    const foreign = pool.filter((t) => !isChineseSubtitleTrack(t));
    if (foreign.length > 0) {
      if (foreign.length > 4) {
        const english = foreign.find((t) => /^en([-_]|$)/i.test(String(t?.lan || "")));
        if (english) return english;
      }
      return foreign[0];
    }
  }
  return pool[0] || null;
}

export async function loadWordbook() {
  try {
    const res = await chrome.storage.local.get({ [WORDBOOK_STORAGE_KEY]: [] });
    return Array.isArray(res[WORDBOOK_STORAGE_KEY]) ? res[WORDBOOK_STORAGE_KEY] : [];
  } catch {
    return [];
  }
}

export async function saveWordbook(items) {
  const safeList = Array.isArray(items) ? items : [];
  await chrome.storage.local.set({ [WORDBOOK_STORAGE_KEY]: safeList });
  return safeList;
}

function createWordbookRecord(entry, existing = null) {
  const now = Date.now();
  const term = String(entry?.term || "").trim();
  const language = String(entry?.language || existing?.language || "").trim();
  const key = normalizeTermKey(term, language);
  const examples = Array.isArray(entry?.examples)
    ? entry.examples
        .filter((ex) => ex && String(ex.sentence || "").trim())
        .map((ex) => ({
          sentence: String(ex.sentence || "").trim(),
          translation: String(ex.translation || "").trim(),
        }))
    : existing?.examples || [];

  return {
    id: existing?.id || `wb_${now}_${Math.random().toString(36).slice(2, 8)}`,
    key,
    term,
    surfaceForm: String(entry?.surfaceForm || existing?.surfaceForm || "").trim(),
    type: entry?.type === "phrase" ? "phrase" : existing?.type === "phrase" ? "phrase" : "word",
    phonetic: String(entry?.phonetic || existing?.phonetic || "").trim(),
    pos: String(entry?.pos || existing?.pos || "").trim(),
    level: String(entry?.level || existing?.level || "").trim(),
    difficulty: Number(entry?.difficulty ?? existing?.difficulty ?? 4) || 4,
    translation: String(entry?.translation || existing?.translation || "").trim(),
    explanation: String(entry?.explanation || existing?.explanation || "").trim(),
    examples,
    videoQuote: String(entry?.videoQuote || existing?.videoQuote || "").trim(),
    videoQuoteTranslation: String(
      entry?.videoQuoteTranslation || existing?.videoQuoteTranslation || ""
    ).trim(),
    videoTime:
      entry?.videoTime != null && Number.isFinite(Number(entry.videoTime))
        ? Number(entry.videoTime)
        : existing?.videoTime ?? null,
    sourceTitle: String(entry?.sourceTitle || existing?.sourceTitle || "").trim(),
    sourceUrl: String(entry?.sourceUrl || existing?.sourceUrl || "").trim(),
    sourceBvid: String(entry?.sourceBvid || existing?.sourceBvid || "").trim(),
    language,
    languageLabel: String(entry?.languageLabel || existing?.languageLabel || language || "").trim(),
    targetLanguage: String(entry?.targetLanguage || existing?.targetLanguage || "").trim(),
    mastered: Boolean(entry?.mastered ?? existing?.mastered ?? false),
    addedAt: existing?.addedAt || now,
    updatedAt: now,
  };
}

export async function addWordbookItem(entry) {
  if (!entry || !String(entry.term || "").trim()) return loadWordbook();
  const list = await loadWordbook();
  const key = normalizeTermKey(entry.term, entry.language || "");
  const existingIdx = list.findIndex(
    (item) => item.key === key || normalizeTermKey(item.term, item.language) === key
  );
  let next;
  if (existingIdx >= 0) {
    const updated = createWordbookRecord(entry, list[existingIdx]);
    next = [updated, ...list.filter((_, idx) => idx !== existingIdx)];
  } else {
    next = [createWordbookRecord(entry), ...list];
  }
  return saveWordbook(next);
}

export async function addManyWordbookItems(entries = []) {
  if (!Array.isArray(entries) || entries.length === 0) return loadWordbook();
  const list = await loadWordbook();
  const mapByKey = new Map();
  for (const item of list) {
    const key = item.key || normalizeTermKey(item.term, item.language);
    mapByKey.set(key, item);
  }
  const newlyAdded = [];
  for (const entry of entries) {
    if (!entry || !String(entry.term || "").trim()) continue;
    const key = normalizeTermKey(entry.term, entry.language || "");
    const existing = mapByKey.get(key);
    const record = createWordbookRecord(entry, existing);
    if (existing) {
      mapByKey.set(key, record);
    } else {
      mapByKey.set(key, record);
      newlyAdded.push(record);
    }
  }
  const existingUpdated = list.map((item) => {
    const key = item.key || normalizeTermKey(item.term, item.language);
    return mapByKey.get(key) || item;
  });
  return saveWordbook([...newlyAdded.reverse(), ...existingUpdated]);
}

export async function removeWordbookItem(idOrKey) {
  const list = await loadWordbook();
  const next = list.filter(
    (item) =>
      item.id !== idOrKey &&
      item.key !== idOrKey &&
      normalizeTermKey(item.term, item.language) !== idOrKey
  );
  return saveWordbook(next);
}

export async function toggleWordbookMastered(id) {
  const list = await loadWordbook();
  const next = list.map((item) =>
    item.id === id ? { ...item, mastered: !item.mastered, updatedAt: Date.now() } : item
  );
  return saveWordbook(next);
}

export async function clearWordbook() {
  return saveWordbook([]);
}

export function subscribeWordbook(listener) {
  if (typeof chrome === "undefined" || !chrome?.storage?.onChanged) {
    return () => {};
  }
  const handler = (changes, areaName) => {
    if (areaName !== "local") return;
    if (Object.prototype.hasOwnProperty.call(changes, WORDBOOK_STORAGE_KEY)) {
      const next = Array.isArray(changes[WORDBOOK_STORAGE_KEY]?.newValue)
        ? changes[WORDBOOK_STORAGE_KEY].newValue
        : [];
      listener(next);
    }
  };
  chrome.storage.onChanged.addListener(handler);
  return () => {
    chrome.storage.onChanged.removeListener(handler);
  };
}

export function useWordbook() {
  const [items, setItems] = React.useState([]);
  const [loading, setLoading] = React.useState(true);

  React.useEffect(() => {
    let active = true;
    loadWordbook().then((loaded) => {
      if (!active) return;
      setItems(loaded);
      setLoading(false);
    });
    const unsub = subscribeWordbook((next) => {
      if (active) setItems(next);
    });
    return () => {
      active = false;
      unsub();
    };
  }, []);

  const keySet = React.useMemo(() => {
    const set = new Set();
    for (const item of items) {
      set.add(item.key || normalizeTermKey(item.term, item.language));
    }
    return set;
  }, [items]);

  const hasTerm = React.useCallback(
    (term, language = "") => keySet.has(normalizeTermKey(term, language)),
    [keySet]
  );

  const addItem = React.useCallback(async (entry) => {
    const next = await addWordbookItem(entry);
    setItems(next);
    return next;
  }, []);

  const addMany = React.useCallback(async (entries) => {
    const next = await addManyWordbookItems(entries);
    setItems(next);
    return next;
  }, []);

  const removeItem = React.useCallback(async (idOrKey) => {
    const next = await removeWordbookItem(idOrKey);
    setItems(next);
    return next;
  }, []);

  const toggleMastered = React.useCallback(async (id) => {
    const next = await toggleWordbookMastered(id);
    setItems(next);
    return next;
  }, []);

  const clearAll = React.useCallback(async () => {
    const next = await clearWordbook();
    setItems(next);
    return next;
  }, []);

  return {
    items,
    loading,
    hasTerm,
    addItem,
    addMany,
    removeItem,
    toggleMastered,
    clearAll,
  };
}

function escapeTsvCell(val) {
  return String(val ?? "")
    .replace(/\r?\n/g, " ")
    .replace(/\t/g, " ")
    .trim();
}

export function exportWordbookToTsv(items = []) {
  const header = [
    "Term",
    "Type",
    "Phonetic",
    "POS",
    "Level",
    "Translation",
    "Explanation",
    "Example",
    "Example Translation",
    "Video Quote",
    "Language",
    "Source Video",
    "Status",
  ].join("\t");
  const rows = items.map((item) => {
    const ex = item.examples?.[0] || {};
    return [
      item.term,
      item.type === "phrase" ? "短语" : "单词",
      item.phonetic,
      item.pos,
      item.level,
      item.translation,
      item.explanation,
      ex.sentence || "",
      ex.translation || "",
      item.videoQuote || "",
      item.languageLabel || item.language || "",
      item.sourceTitle || "",
      item.mastered ? "已掌握" : "学习中",
    ]
      .map(escapeTsvCell)
      .join("\t");
  });
  return "\uFEFF" + [header, ...rows].join("\n");
}
